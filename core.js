/* Core parsing + matching. Works in the browser (window.EcoCore) and in Node (module.exports). */
(function (root) {
  'use strict';

  async function pageItems(page) {
    const vp = page.getViewport({ scale: 1 });
    const tc = await page.getTextContent();
    const out = [];
    for (const it of tc.items) {
      if (!it.str || !it.str.trim()) continue;
      const st = tc.styles[it.fontName] || {};
      const h = Math.hypot(it.transform[2], it.transform[3]) || it.height || 9;
      out.push({
        str: it.str, x: it.transform[4], y: vp.height - it.transform[5], w: it.width, h,
        font: it.fontName, sans: /sans/i.test(st.fontFamily || '') && !/^serif/i.test(st.fontFamily || '')
      });
    }
    return { items: out, width: vp.width, height: vp.height };
  }

  // Group items into lines (same baseline), left to right.
  function toLines(items, tol) {
    tol = tol || 2;
    const sorted = items.slice().sort((a, b) => a.y - b.y || a.x - b.x);
    const lines = [];
    for (const it of sorted) {
      let ln = lines.length ? lines[lines.length - 1] : null;
      if (!ln || Math.abs(ln.y - it.y) > tol) { ln = { y: it.y, items: [] }; lines.push(ln); }
      ln.items.push(it);
    }
    for (const ln of lines) {
      ln.items.sort((a, b) => a.x - b.x);
      let text = '', prev = null;
      for (const it of ln.items) {
        if (prev) {
          const gap = it.x - (prev.x + prev.w);
          if (gap > prev.h * 0.15 && !/\s$/.test(text) && !/^\s/.test(it.str)) text += ' ';
        }
        text += it.str; prev = it;
      }
      ln.text = text.replace(/\s+/g, ' ').trim();
      ln.x = ln.items[0].x;
      const last = ln.items[ln.items.length - 1];
      ln.right = last.x + last.w;
      ln.h = Math.max(...ln.items.map(i => i.h));
      const chars = ln.items.reduce((s, i) => s + i.str.length, 0);
      ln.cw = chars ? ln.items.reduce((s, i) => s + i.w, 0) / chars : ln.h * 0.5;
    }
    return lines;
  }

  /* ---------- ProQuest export ---------- */
  const NOISE = [/PDF GENERATED BY PROQUEST\.COM/i, /^Document \d+ of \d+$/, /^Page \d+ of \d+$/];

  async function parseProquest(pdf, onProgress) {
    const all = [];
    for (let p = 1; p <= pdf.numPages; p++) {
      const pg = await pdf.getPage(p);
      const { items } = await pageItems(pg);
      for (const ln of toLines(items)) {
        if (NOISE.some(r => r.test(ln.text))) continue;
        ln.page = p; all.push(ln);
      }
      if (onProgress) onProgress(p / pdf.numPages);
    }
    let outline = [];
    try {
      const ol = (await pdf.getOutline()) || [];
      outline = ol.map(o => o.title);
    } catch (e) { /* no bookmarks */ }

    const marks = [];
    all.forEach((ln, i) => { if (/^ProQuest document link$/i.test(ln.text)) marks.push(i); });
    const useOutline = outline.length === marks.length;
    const bodyRight = percentile(all.filter(l => l.text.length > 60).map(l => l.right), 0.95);

    const articles = marks.map((m, k) => {
      const end = k + 1 < marks.length ? marks[k + 1] : all.length;
      const seg = all.slice(m + 1, end);
      const title = useOutline ? outline[k] : (all[m - 1] ? all[m - 1].text : 'Untitled');
      const ft = seg.findIndex(l => /^FULL TEXT$/i.test(l.text));
      const det = seg.findIndex(l => /^DETAILS$/i.test(l.text));
      const bodyLines = seg.slice(ft >= 0 ? ft + 1 : 0, det >= 0 ? det : seg.length);
      const meta = parseMeta(det >= 0 ? seg.slice(det + 1) : []);
      const fp = parseInt(meta['First page'] || meta['Pages'] || '', 10);
      return {
        id: k, title,
        section: meta['Section'] || '',
        page: isNaN(fp) ? null : fp,
        pages: meta['Pages'] || meta['First page'] || '',
        subject: meta['Subject'] || '', location: meta['Location'] || '',
        docType: meta['Document type'] || '',
        pdfPage: all[m].page,
        paragraphs: toParagraphs(bodyLines, bodyRight)
      };
    }).filter(a => !/Tbl Of Contents/i.test(a.docType) && !/^_TVM/.test((a.paragraphs[0] || {}).t || ''));
    const dateM = all.slice(0, 400).map(l => l.text.match(/^Publication date:\s*(.+)$/)).find(Boolean);
    return { articles, date: dateM ? dateM[1].trim() : '' };
  }

  function parseMeta(lines) {
    const meta = {}; let key = null;
    for (const ln of lines) {
      if (/^LINKS$/.test(ln.text)) break;
      const m = ln.text.match(/^([A-Z][A-Za-z\- ]{1,40}):\s*(.*)$/);
      if (m && ln.x < 80) { key = m[1].trim(); meta[key] = m[2].trim(); }
      else if (key) meta[key] += ' ' + ln.text;
    }
    return meta;
  }

  // Reflow: a line ends a paragraph if the next line's first word would have fit on it.
  function toParagraphs(lines, right) {
    const paras = []; let cur = [];
    for (let i = 0; i < lines.length; i++) {
      const ln = lines[i], next = lines[i + 1];
      cur.push(ln.text);
      let brk = !next;
      if (next) {
        const firstWord = next.text.split(' ')[0] || '';
        brk = ln.right + (firstWord.length + 1) * next.cw < right - 2;
      }
      if (brk) {
        let t = '';
        for (const s of cur) t += (t && !/[-—–]$/.test(t) ? ' ' : '') + s;
        const single = cur.length === 1;
        paras.push({ t, h: single && t.length < 70 && !/[.?!:;,"”’)]$/.test(t) && i < lines.length - 1 });
        cur = [];
      }
    }
    return paras;
  }

  function percentile(arr, q) {
    if (!arr.length) return 500;
    const s = arr.slice().sort((a, b) => a - b);
    return s[Math.min(s.length - 1, Math.floor(q * s.length))];
  }

  /* ---------- Economist table of contents ---------- */
  async function parseToc(pdf) {
    const sections = []; let issue = '', coverPage = null, cover = null;
    for (let p = 1; p <= pdf.numPages; p++) {
      const pg = await pdf.getPage(p);
      const { items } = await pageItems(pg);
      if (!issue) {
        const d = items.map(i => i.str.match(/[A-Z][a-z]+ \d{1,2}(st|nd|rd|th) \d{4}/)).find(Boolean);
        if (d) issue = d[0];
      }
      const numRe = /^\d{1,3}(\s|$)/;
      const numXs = items.filter(i => !i.sans && numRe.test(i.str.trim()) && i.y > 80).map(i => i.x).sort((a, b) => a - b);
      const clusters = [];
      for (const x of numXs) {
        const c = clusters[clusters.length - 1];
        if (c && x - c.max < 8) { c.max = x; c.n++; } else clusters.push({ min: x, max: x, n: 1 });
      }
      const cols = clusters.filter(c => c.n >= 2).map(c => c.min - 4);
      if (!cols.length) continue;
      if (!cover && typeof document !== 'undefined' && (p === 1 || items.some(i => /^On the cover/i.test(i.str.trim())))) {
        try { cover = await findCover(pg, pdf, items); } catch (e) { cover = null; }
      }
      if (coverPage == null) {
        const side = toLines(items.filter(i => i.x < cols[0] && i.y > 80)).map(l => l.text).join(' ');
        const cm = side.match(/On the cover(.*?)\bpage\s+(\d+)/i);
        if (cm) coverPage = parseInt(cm[2], 10);
      }
      const byCol = cols.map(() => []);
      for (const it of items) {
        if (it.y < 80 || it.h > 14) continue;
        let ci = -1;
        cols.forEach((cx, j) => { if (it.x >= cx) ci = j; });
        if (ci >= 0) byCol[ci].push(it);
      }
      for (const colItems of byCol) {
        const lines = toLines(colItems);
        let section = null, entry = null, prevY = -99, prevHeader = false;
        for (const ln of lines) {
          const gap = ln.y - prevY; prevY = ln.y;
          const first = ln.items[0];
          const allSans = ln.items.every(i => i.sans);
          if (!first.sans && numRe.test(first.str.trim())) {
            const num = parseInt(first.str, 10);
            entry = { page: num, kicker: '', title: '', numFont: first.font };
            const rest = first.str.trim().replace(/^\d+\s*/, '');
            if (rest) entry.kicker = rest;
            for (const it of ln.items.slice(1)) addText(entry, it);
            if (!section) { section = { name: '', entries: [] }; sections.push(section); }
            section.entries.push(entry); prevHeader = false;
          } else if (allSans) {
            if (prevHeader && gap < ln.h * 1.6 && section) section.name += ' ' + ln.text;
            else { section = { name: ln.text, entries: [] }; sections.push(section); }
            entry = null; prevHeader = true;
          } else if (entry && gap < ln.h * 1.5) {
            for (const it of ln.items) addText(entry, it);
          } else { entry = null; prevHeader = false; }
        }
      }
    }
    const clean = sections.filter(s => s.entries.length).map(s => ({
      name: s.name.trim(),
      entries: s.entries.map(e => {
        let kicker = tidy(e.kicker), title = tidy(e.title);
        if (!title) { title = kicker; kicker = ''; }
        return { page: e.page, kicker, title };
      })
    }));
    let name = '';
    if (coverPage != null) {
      const hits = [];
      clean.forEach(s => s.entries.forEach(e => { if (e.page === coverPage) hits.push({ s, e }); }));
      const h = hits.find(x => /leader/i.test(x.s.name)) || hits[0];
      if (h) name = h.e.title;
    }
    return { sections: clean, issue, coverPage, name, cover: cover || '' };
  }
  /* Cover picture: the portrait image sitting just above the "On the cover" note (else the largest portrait image).
     The page is rendered and that area cropped, so any image format the PDF uses works. */
  const mul = (m, n) => [m[0] * n[0] + m[2] * n[1], m[1] * n[0] + m[3] * n[1], m[0] * n[2] + m[2] * n[3], m[1] * n[2] + m[3] * n[3], m[0] * n[4] + m[2] * n[5] + m[4], m[1] * n[4] + m[3] * n[5] + m[5]];
  async function findCover(page, pdf, items) {
    const OPS = (typeof pdfjsLib !== 'undefined' && pdfjsLib.OPS) || {};
    const vp = page.getViewport({ scale: 1 });
    const ops = await page.getOperatorList();
    let ctm = [1, 0, 0, 1, 0, 0]; const stack = [], imgs = [];
    for (let i = 0; i < ops.fnArray.length; i++) {
      const fn = ops.fnArray[i], a = ops.argsArray[i];
      if (fn === OPS.save) stack.push(ctm);
      else if (fn === OPS.restore) ctm = stack.pop() || [1, 0, 0, 1, 0, 0];
      else if (fn === OPS.transform) ctm = mul(ctm, a);
      else if (fn === OPS.paintFormXObjectBegin) { stack.push(ctm); if (a && a[0]) ctm = mul(ctm, a[0]); }
      else if (fn === OPS.paintFormXObjectEnd) ctm = stack.pop() || [1, 0, 0, 1, 0, 0];
      else if (fn === OPS.paintImageXObject || fn === OPS.paintJpegXObject || fn === OPS.paintInlineImageXObject) {
        const pts = [[0, 0], [1, 0], [0, 1], [1, 1]].map(([x, y]) => vp.convertToViewportPoint(ctm[0] * x + ctm[2] * y + ctm[4], ctm[1] * x + ctm[3] * y + ctm[5]));
        const xs = pts.map(p => p[0]), ys = pts.map(p => p[1]);
        const b = { x0: Math.min(...xs), y0: Math.min(...ys), x1: Math.max(...xs), y1: Math.max(...ys) };
        b.w = b.x1 - b.x0; b.h = b.y1 - b.y0;
        if (b.w > 40 && b.h > 40) imgs.push(b);
      }
    }
    const portrait = imgs.filter(b => b.h > b.w * 1.05);
    if (!portrait.length) return null;
    const lab = items.find(i => /^On the cover/i.test(i.str.trim()));
    let pick = null;
    if (lab) {
      const above = portrait.filter(b => b.y1 <= lab.y + 4 && lab.y - b.y1 < 60 && lab.x >= b.x0 - 20 && lab.x <= b.x1);
      pick = above.sort((p, q) => (lab.y - p.y1) - (lab.y - q.y1))[0];
    }
    if (!pick) pick = portrait.sort((p, q) => q.w * q.h - p.w * p.h)[0];
    const scale = Math.min(4, 420 / pick.w);
    const v = page.getViewport({ scale });
    const cv = document.createElement('canvas'); cv.width = Math.ceil(v.width); cv.height = Math.ceil(v.height);
    await page.render({ canvasContext: cv.getContext('2d'), viewport: v }).promise;
    const out = document.createElement('canvas');
    out.width = Math.round(pick.w * scale); out.height = Math.round(pick.h * scale);
    out.getContext('2d').drawImage(cv, pick.x0 * scale, pick.y0 * scale, out.width, out.height, 0, 0, out.width, out.height);
    return out.toDataURL('image/jpeg', 0.82);
  }
  function addText(entry, it) {
    const k = it.font === entry.numFont ? 'kicker' : 'title';
    const s = entry[k];
    entry[k] = s && !/-$/.test(s) ? s + ' ' + it.str : s + it.str;
  }
  function tidy(s) { return (s || '').replace(/\s+/g, ' ').replace(/\b([A-Z]{2,}) s\b/g, '$1s').trim(); }

  /* ---------- Matching ---------- */
  const STOP = new Set('the and for with from that this into over under about after its their are was were has have how why what who will not but out new all more less than between'.split(' '));
  function stems(s) {
    return (s || '').toLowerCase().normalize('NFD').replace(/[̀-ͯ]/g, '')
      .replace(/[’']s\b/g, '').split(/[^a-z0-9]+/)
      .filter(w => w.length >= 3 && !STOP.has(w))
      .map(w => (w.length >= 6 ? w.slice(0, 5) : w.replace(/s$/, '')));
  }
  function normSec(s) { return (s || '').toLowerCase().replace(/&/g, 'and').replace(/[^a-z]/g, ''); }

  function match(toc, pq) {
    const entries = [];
    toc.sections.forEach((s, si) => s.entries.forEach((e, ei) => entries.push({ si, ei, e, sec: s.name })));
    const arts = pq.articles.map(a => {
      const body = a.paragraphs.slice(0, 12).map(p => p.t).join(' ').slice(0, 3000);
      return { a, titleSet: new Set(stems(a.title)), docSet: new Set(stems(body + ' ' + a.subject + ' ' + a.location)) };
    });
    const textScore = (e, x) => {
      let s = 0;
      for (const t of new Set(stems(e.kicker + ' ' + e.title))) {
        if (x.titleSet.has(t)) s += 3; else if (x.docSet.has(t)) s += 1;
      }
      return s;
    };
    const pairs = [];
    entries.forEach((en, i) => arts.forEach((x, j) => {
      if (x.a.page == null) return;
      const d = Math.abs(x.a.page - en.e.page);
      if (d > 1) return;
      const sameSec = normSec(x.a.section) === normSec(en.sec);
      const ts = textScore(en.e, x);
      if (d === 1 && (!sameSec || ts < 2)) return;
      pairs.push({ i, j, score: (d === 0 ? 1000 : 0) + (sameSec ? 100 : 0) + ts });
    }));
    pairs.sort((a, b) => b.score - a.score);
    const usedE = new Set(), usedA = new Set();
    for (const p of pairs) {
      if (usedE.has(p.i) || usedA.has(p.j)) continue;
      usedE.add(p.i); usedA.add(p.j);
      entries[p.i].e.article = arts[p.j].a.id;
    }
    const extra = pq.articles.filter(a => !usedA.has(arts.findIndex(x => x.a === a)));
    return { toc, extra };
  }

  // Contents with article ids attached; articles not in the contents are slotted into their section.
  function buildContents(tocRaw, articles) {
    const order = (a, b) => (a.page || 999) - (b.page || 999);
    if (!tocRaw) {
      const secs = [];
      for (const a of articles.slice().sort(order)) {
        const nm = a.section || 'Other';
        let s = secs.find(x => x.name === nm); if (!s) secs.push(s = { name: nm, entries: [] });
        s.entries.push({ page: a.page, kicker: '', title: a.title, article: a.id, pqOnly: true });
      }
      return { sections: secs, matched: 0, tocCount: 0 };
    }
    const toc = JSON.parse(JSON.stringify({ sections: tocRaw.sections }));
    const { extra } = match(toc, { articles });
    let matched = 0, tocCount = 0;
    toc.sections.forEach(s => s.entries.forEach(e => { tocCount++; if (e.article != null) matched++; }));
    const other = { name: 'Other articles', entries: [] };
    for (const a of extra) {
      const s = toc.sections.find(x => normSec(x.name) === normSec(a.section)) || other;
      s.entries.push({ page: a.page, kicker: '', title: a.title, article: a.id, pqOnly: true });
      s.entries.sort(order);
    }
    if (other.entries.length) toc.sections.push(other);
    return { sections: toc.sections, matched, tocCount };
  }

  const api = { parseProquest, parseToc, match, buildContents };
  if (typeof module !== 'undefined' && module.exports) module.exports = api;
  else root.EcoCore = api;
})(typeof window !== 'undefined' ? window : globalThis);
